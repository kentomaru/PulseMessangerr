/** Маркер связи «группа = обсуждение канала» и его очистка.
 *  Живёт в клиентобезопасном модуле: используется и в серверных роутах,
 *  и в интерфейсе (описание чата не должно показывать служебную строку). */
export const DISCUSSION_MARKER = "pulse-discussion-of:";

/**
 * Убирает служебный маркер «обсуждение канала» из описания чата.
 * Маркер может идти первой строкой или стоять в начале той же строки —
 * пользователю показываем только сам текст описания.
 */
export function stripDiscussionMarker(about: string | null | undefined): string {
  const a = about ?? "";
  return a.replace(/^pulse-discussion-of:[0-9a-f-]+\s*/i, "");
}
